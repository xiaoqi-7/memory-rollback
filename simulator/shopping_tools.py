import json
import os
from functools import lru_cache
from typing import Any, Dict, List, Optional

# Standalone default; AgentRunner overrides this from domain config data_source.
_DEFAULT_DB_DIR = os.path.join(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
    "data",
    "controlled_benchmark",
    "shopping",
    "catalog",
)
_CONFIGURED_DB_DIR = _DEFAULT_DB_DIR


def _db_dir() -> str:
    return _CONFIGURED_DB_DIR


def configure_db_dir(path: str) -> None:
    """Select the catalog derived from the active domain data_source."""
    global _CONFIGURED_DB_DIR
    _CONFIGURED_DB_DIR = os.path.abspath(path)
    _load.cache_clear()


@lru_cache(maxsize=None)
def _load(filename: str) -> Any:
    """Load and cache a catalog file. Returns an empty container if missing."""
    path = os.path.join(_db_dir(), filename)
    if not os.path.exists(path):
        raise FileNotFoundError(
            f"Catalog file not found: {path}. "
            "Expected <data_source>/catalog for shopping."
        )
    with open(path, "r", encoding="utf-8") as f:
        return json.load(f)


def _products() -> List[Dict[str, Any]]:
    return _load("products.json")


def _pricing() -> Dict[str, Any]:
    return _load("pricing.json")


def _shipping() -> Dict[str, Any]:
    return _load("shipping.json")


def search_product(query: str) -> dict:
    """Search for products whose name, brand, category, or color match the query.

    Matching is a simple case-insensitive token overlap against the catalog
    generated by ``data/build_catalog.py``.
    """
    tokens = [t for t in query.lower().split() if t]
    results = []
    for product in _products():
        haystack = " ".join(
            str(product.get(field, ""))
            for field in ("name", "brand", "category", "color", "description")
        ).lower()
        if not tokens or any(token in haystack for token in tokens):
            results.append(
                {
                    "id": product["id"],
                    "name": product["name"],
                    "category": product["category"],
                    "color": product.get("color"),
                    "size": product.get("size"),
                    "price": product["price"],
                    "in_stock": product.get("in_stock", True),
                }
            )

    return {
        "query": query,
        "results": results,
        "count": len(results),
    }


def compare_price(product_id: str, competitor_ids: Optional[List[str]] = None) -> dict:
    """Compare a product's price with competitor offers from the pricing table."""
    pricing = _pricing()
    entry = pricing.get(product_id)
    if entry is None:
        return {"product_id": product_id, "error": "product not found in pricing table"}

    competitors = entry.get("offers", [])
    if competitor_ids:
        wanted = set(competitor_ids)
        competitors = [c for c in competitors if c.get("competitor") in wanted]

    return {
        "product_id": product_id,
        "price": entry.get("base_price"),
        "competitors": competitors,
        "best_option": entry.get("best_seller"),
        "best_price": entry.get("best_price"),
    }


def check_shipping(product_id: str, destination: str) -> dict:
    """Check shipping availability and estimated delivery for a destination."""
    shipping = _shipping()
    routes = shipping.get(product_id)
    if routes is None:
        return {"product_id": product_id, "destination": destination, "error": "product not found in shipping table"}

    row = routes.get(destination)
    if row is None:
        return {
            "product_id": product_id,
            "destination": destination,
            "available": False,
            "note": "destination not served",
        }

    return {
        "product_id": product_id,
        "destination": destination,
        "available": row.get("available", False),
        "estimated_days": row.get("estimated_days"),
        "shipping_cost": row.get("shipping_cost"),
    }
